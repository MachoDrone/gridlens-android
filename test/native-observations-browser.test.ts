import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import playwright from "../vendor/gridlens/node_modules/playwright/index.js";
import { startAndroidRuntime, SESSION_COOKIE } from "../runtime/server.ts";
import { networkView, parsePcNetworkRecord, parseSavedObservation } from "../vendor/gridlens/src/fleet/pc-observations.ts";
import type { PcNetworkUpdate, PcUpdate } from "../vendor/gridlens/src/fleet/pc-observations.ts";

// Generated by the production Java readers/serializer. The native unit test
// compares this checked fixture with its generated output on every native run.
interface NativeFixture {
  schema: 1;
  checkedAtMs: number;
  cases: {
    name: string;
    pcId: string;
    address: string;
    expectedPublicIp: string | null;
    expectedPrivateIp: string | null;
    updates: (PcUpdate | PcNetworkUpdate)[];
    rejectedUpdates?: unknown[];
  }[];
}

test("native-generated independent readings survive API rejection, storage reopening and Fleet rendering", { timeout: 90_000 }, async () => {
  const fixture = JSON.parse(await readFile(process.env.GRIDLENS_NATIVE_OBSERVATIONS_FILE
    ?? resolve("test/fixtures/native-observations.json"), "utf8")) as NativeFixture;
  assert.equal(fixture.schema, 1);
  assert.ok(fixture.cases.length >= 6);
  const addresses = fixture.cases.map(value => value.address);
  assert.equal(new Set(addresses).size, addresses.length);
  const dataDirectory = await mkdtemp(join(tmpdir(), "gridlens-native-delivery-"));
  await writeFile(join(dataDirectory, "hosts.json"), "[]");
  await writeFile(join(dataDirectory, "real200.json"), "[]");
  const now = fixture.checkedAtMs + 1000;
  const empty = async () => ({ hosts: [], nextRefreshAtMs: now + 60000 });
  const start = (preferredPort: number) => startAndroidRuntime({ dataDirectory, directory: resolve("dist/runtime/web"), preferredPort,
    providers: { now: () => now, metadataProvider: empty, nodeInfoProvider: empty, jobProvider: empty,
      queueProvider: empty, solProvider: empty, nosProvider: empty, stakingProvider: empty } });
  let runtime = await start(0);
  const close = async () => {
    runtime.server.closeAllConnections();
    await new Promise<void>(accept => runtime.server.close(() => accept()));
  };
  const origin = `http://127.0.0.1:${runtime.port}`;
  const native = () => ({ "X-GridLens-Token": runtime.token, "Content-Type": "application/json" });
  const browser = await playwright.chromium.launch({ headless: true,
    ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
  try {
    const created = await fetch(origin + "/mobile/fleets", { method: "POST", headers: native(),
      body: JSON.stringify({ op: "create", name: "Native delivery fixture", addresses,
        pcMetadata: fixture.cases.map(value => ({ address: value.address, pcId: value.pcId, pcName: value.name,
          ipAddresses: [value.expectedPrivateIp ?? value.expectedPublicIp ?? "10.0.0.2"], observedAtMs: fixture.checkedAtMs })) }) });
    assert.equal(created.status, 200);
    const { fleetId } = await created.json() as { fleetId: string };
    const post = async (update: unknown, expectedStatus: number) => {
      const response = await fetch(origin + "/mobile/observations", { method: "POST", headers: native(),
        body: JSON.stringify({ schema: 1, fleetId, updates: [update] }) });
      assert.equal(response.status, expectedStatus, await response.text());
    };
    for (const value of fixture.cases) {
      for (const update of value.updates) {
        if ("pcId" in update) {
          assert.equal(update.pcId, value.pcId);
          assert.deepEqual(Object.keys(update).sort(), ["network", "pcId"], "PC IP must not assert a node binding or monitoring status");
        } else {
          assert.equal(update.address, value.address);
          assert.equal(update.binding.pcId, value.pcId);
          assert.ok([update.network, update.rewards, update.gpu].filter(Boolean).length <= 1,
            "native delivery must isolate each source before HTTP validation");
        }
        await post(update, 200);
      }
      for (const rejected of value.rejectedUpdates ?? []) await post(rejected, 400);
      // A separately malformed GPU payload must fail closed without poisoning
      // successful network/reward deliveries from the same verified binding.
      const binding = value.updates.find((update): update is PcUpdate => "binding" in update)?.binding
        ?? { pcId: value.pcId, runtime: "docker", wrapperId: null, nodeContainerId: "b".repeat(64) };
      await post({ address: value.address, binding,
        gpu: { schema: 2, status: "ok", samples: "malformed" } }, 400);
    }
    const retained = fixture.cases[0]!;
    const retainedBinding = retained.updates.find((update): update is PcUpdate => "binding" in update)?.binding;
    assert.ok(retainedBinding, "the first native case includes a retained rewards reading");
    await post({ address: retained.address, binding: retainedBinding,
      rewards: { schema: 1, address: retained.address, status: "unavailable", observedAtMs: now } }, 200);
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    const forbidden: string[] = [], errors: string[] = [];
    await context.route("**/*", async route => {
      if (new URL(route.request().url()).origin !== origin || route.request().method() !== "GET") {
        forbidden.push(route.request().url()); await route.abort(); return;
      }
      await route.continue();
    });
    await context.addCookies([{ name: SESSION_COOKIE, value: runtime.token, url: origin, httpOnly: true, sameSite: "Strict" }]);
    const page = await context.newPage();
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(origin + `/?scenario=fleet:${fleetId}`);
    await page.locator('#ip-display-toggle').click();
    const assertReadings = async () => {
      for (const value of fixture.cases) {
        const response = await fetch(origin + `/mobile/observations?fleet=${fleetId}&address=${value.address}`, { headers: native() });
        assert.equal(response.status, 200);
        const result = await response.json() as { host: unknown; pcNetworks?: unknown[] };
        const saved = result.host === null ? undefined : parseSavedObservation(result.host);
        const pcNetwork = result.pcNetworks?.map(parsePcNetworkRecord).find(record => record.pcId === value.pcId);
        const view = networkView(pcNetwork ?? saved, now);
        assert.equal(view.publicIp, value.expectedPublicIp, value.name);
        assert.equal(view.privateIp, value.expectedPrivateIp, value.name);
        for (const update of value.updates) if ("pcId" in update) {
          assert.ok(pcNetwork);
          assert.equal(pcNetwork.network.source, update.network.source);
          assert.equal(pcNetwork.network.observedAtMs, update.network.observedAtMs);
          assert.equal(pcNetwork.network.publicFailure, update.network.publicFailure);
          assert.equal(pcNetwork.network.privateFailure, update.network.privateFailure);
          assert.equal(pcNetwork.network.retryAtMs, update.network.retryAtMs);
        }
        const expected = `${value.expectedPublicIp ?? "−"} / ${value.expectedPrivateIp ?? "−"}`;
        await page.waitForFunction(({ address, expected }) => document.querySelector(
          `#fleet-rows > tr[data-host="${address}"] td[data-col="ip"]`)?.textContent === expected,
        { address: value.address, expected });
        for (const update of value.updates) if ("address" in update && update.rewards?.status === "ok") {
          assert.equal(saved?.lastGoodRewards?.amount, update.rewards.amount);
          assert.equal(saved?.lastGoodRewards?.observedAtMs, update.rewards.observedAtMs);
          const amount = page.locator(`#fleet-rows > tr[data-host="${value.address}"] td[data-col="rewards"] a`);
          assert.match(await amount.getAttribute("aria-label") ?? "", /Last read by GridLens/);
          assert.equal(await amount.evaluate(element => getComputedStyle(element).color), "rgb(15, 92, 43)");
          assert.equal(await amount.evaluate(element => getComputedStyle(element).fontWeight), "400");
          assert.equal(await amount.evaluate(element => element.closest('td')!.classList.contains("metadata-retained")),
            value.address === retained.address, "current and retained readings keep distinct status across runtime reopening");
        }
      }
      assert.equal(await page.locator('.mobile-rewards-age').count(), 0);
    };
    await assertReadings();
    // Reopen the actual persisted runtime, not just the browser's in-memory view.
    await page.goto("about:blank");
    const port = runtime.port;
    await close();
    runtime = await start(port);
    assert.equal(runtime.port, port);
    await context.addCookies([{ name: SESSION_COOKIE, value: runtime.token, url: origin, httpOnly: true, sameSite: "Strict" }]);
    await page.goto(origin + `/?scenario=fleet:${fleetId}`);
    await assertReadings();
    assert.deepEqual(forbidden, []);
    assert.deepEqual(errors, []);
    await context.close();
  } finally {
    await browser.close(); await close();
    await rm(dataDirectory, { recursive: true, force: true });
  }
});
